/**
 * Markdown -> HTML.
 *
 * Pure and deterministic: no DOM, no network, no filesystem. That is what lets
 * the same function run in the browser for the live preview and on the server
 * for the PDF, and is the only reason the two can be guaranteed to match.
 *
 * The plugin order matters more than it looks. Sanitisation runs immediately
 * after raw HTML is parsed and *before* KaTeX and syntax highlighting inject
 * their own markup - otherwise the allowlist would have to whitelist every
 * class those two emit, which is a much larger hole than it sounds.
 */

export type ExtractedHeading = {
  /** 1 for h1, 6 for h6. */
  depth: number;
  /** Plain text, without any auto-generated section number. */
  text: string;
  /** "2.1.3" when heading numbering is on, otherwise null. */
  number: string | null;
  /** Anchor id, as generated by rehype-slug. */
  id: string;
};

export type RenderedMarkdown = {
  html: string;
  headings: ExtractedHeading[];
  frontMatter: Record<string, unknown>;
  /** Front matter `title`, else the first h1, else null. */
  title: string | null;
  wordCount: number;
};

export type MarkdownRenderOptions = {
  markdown: MarkdownConfig;
  structure: StructureConfig;
};

