// Front matter
// ---------------------------------------------------------------------------

/**
 * Pulls the YAML block out of the tree and into `store`.
 *
 * remark-frontmatter only *recognises* the block - without this it would be
 * silently dropped on the way to HTML and its metadata lost. In "render" mode
 * we keep it visible by turning it into a fenced code block instead.
 */
function remarkFrontMatter(store: { data: Record<string, unknown> }, mode: MarkdownConfig["frontMatter"]) {
  return () => (tree: MdastRoot) => {
    const kept: RootContent[] = [];

    for (const node of tree.children) {
      if (node.type !== "yaml") {
        kept.push(node);
        continue;
      }

      if (mode === "parse") {
        try {
          const parsed = loadYaml(node.value);
          if (parsed && typeof parsed === "object" && !Array.isArray(parsed)) {
            store.data = parsed as Record<string, unknown>;
          }
        } catch {
          // Malformed YAML is the author's problem, not a reason to fail the
          // whole render. Drop it and carry on.
        }
      }

      if (mode === "render") {
        kept.push({ type: "code", lang: "yaml", value: node.value });
      }
    }

    tree.children = kept;
  };
}

